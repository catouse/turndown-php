import { createHash } from 'node:crypto';
import { access, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const projectRoot = resolve(siteRoot, '..');
const outputFile = resolve(siteRoot, 'app/php-files.generated.ts');
const publicLicenseDirectory = resolve(siteRoot, 'public/licenses');

const sourceRoots = [
  {
    source: resolve(projectRoot, 'src'),
    target: '/app/src',
  },
  {
    source: resolve(projectRoot, 'vendor/masterminds/html5/src'),
    target: '/app/vendor/masterminds/html5/src',
  },
];

const bootstrapPhp = String.raw`<?php

declare(strict_types=1);

spl_autoload_register(static function (string $class): void {
    $prefixes = [
        'Catouse\\Turndown\\' => '/app/src/',
        'Masterminds\\' => '/app/vendor/masterminds/html5/src/',
    ];

    foreach ($prefixes as $prefix => $directory) {
        if (!str_starts_with($class, $prefix)) {
            continue;
        }

        $relative = str_replace('\\', '/', substr($class, strlen($prefix)));
        $file = $directory . $relative . '.php';

        if (is_file($file)) {
            require $file;
        }

        return;
    }
});
`;

const bridgePhp = String.raw`<?php

declare(strict_types=1);

use Catouse\Turndown\Plugin\Gfm;
use Catouse\Turndown\TurndownService;

require_once '/app/bootstrap.php';

/** @return array{ok: bool, markdown?: string, error?: string} */
function turndown_wasm_convert(string $payloadJson): array
{
    try {
        $payload = json_decode($payloadJson, true, 512, JSON_THROW_ON_ERROR);

        if (!is_array($payload)) {
            throw new InvalidArgumentException('The conversion payload must be an object.');
        }

        $html = $payload['html'] ?? '';
        $options = $payload['options'] ?? [];

        if (!is_string($html) || !is_array($options)) {
            throw new InvalidArgumentException('The conversion payload is invalid.');
        }

        $service = new TurndownService($options);

        if (($payload['gfm'] ?? false) === true) {
            $service->use(new Gfm());
        }

        return [
            'ok' => true,
            'markdown' => base64_encode($service->turndown($html)),
        ];
    } catch (Throwable $error) {
        return [
            'ok' => false,
            'error' => base64_encode($error->getMessage()),
        ];
    }
}
`;

async function exists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function collectPhpFiles(root) {
  const files = [];

  async function visit(directory) {
    const entries = await readdir(directory, { withFileTypes: true });
    entries.sort((left, right) => left.name.localeCompare(right.name));

    for (const entry of entries) {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) {
        await visit(path);
      } else if (entry.isFile() && entry.name.endsWith('.php')) {
        files.push(path);
      }
    }
  }

  await visit(root);
  return files;
}

const sourcesAvailable = (
  await Promise.all(sourceRoots.map(({ source }) => exists(source)))
).every(Boolean);

if (!sourcesAvailable) {
  if (await exists(outputFile)) {
    console.log('Using the committed PHP runtime bundle.');
    process.exit(0);
  }

  throw new Error('turndown-php sources are unavailable and no runtime bundle exists.');
}

const files = [
  { path: '/app/bootstrap.php', contents: bootstrapPhp },
  { path: '/app/bridge.php', contents: bridgePhp },
];

for (const { source, target } of sourceRoots) {
  for (const path of await collectPhpFiles(source)) {
    const relativePath = relative(source, path).split(sep).join('/');
    files.push({
      path: `${target}/${relativePath}`,
      contents: await readFile(path),
    });
  }
}

files.sort((left, right) => left.path.localeCompare(right.path));

const hash = createHash('sha256');
for (const file of files) {
  hash.update(file.path);
  hash.update('\0');
  hash.update(file.contents);
  hash.update('\0');
}

const generatedFiles = files.map((file) => ({
  path: file.path,
  base64: Buffer.from(file.contents).toString('base64'),
}));

const output = `// Generated by scripts/generate-php-runtime.mjs. Do not edit by hand.\n` +
  `export const phpRuntimeBuild = ${JSON.stringify({
    fingerprint: hash.digest('hex'),
    fileCount: generatedFiles.length,
  }, null, 2)} as const;\n\n` +
  `export const phpRuntimeFiles = ${JSON.stringify(generatedFiles, null, 2)} as const;\n`;

await mkdir(dirname(outputFile), { recursive: true });
await writeFile(outputFile, output);

const wasmPackages = [
  'php-wasm',
  'php-wasm-dom',
  'php-wasm-libxml',
  'php-wasm-mbstring',
  'php-wasm-xml',
];
const notices = await Promise.all(
  wasmPackages.map(async (packageName) =>
    readFile(resolve(siteRoot, `node_modules/${packageName}/NOTICE`), 'utf8'),
  ),
);
const apacheLicense = await readFile(resolve(siteRoot, 'node_modules/php-wasm/LICENSE'), 'utf8');
const html5License = await readFile(
  resolve(projectRoot, 'vendor/masterminds/html5/LICENSE.txt'),
  'utf8',
);

await mkdir(publicLicenseDirectory, { recursive: true });
await writeFile(
  resolve(publicLicenseDirectory, 'THIRD_PARTY_NOTICES.txt'),
  `${notices.join('\n\n---\n\n')}\n\n` +
    `PHP is distributed under the PHP License 3.01: https://www.php.net/license/3_01.txt\n` +
    `HTML5-PHP is distributed under the MIT license included alongside this notice.\n`,
);
await writeFile(resolve(publicLicenseDirectory, 'APACHE-2.0.txt'), apacheLicense);
await writeFile(resolve(publicLicenseDirectory, 'HTML5-PHP.txt'), html5License);

console.log(`Generated ${generatedFiles.length} PHP runtime files and third-party notices.`);
